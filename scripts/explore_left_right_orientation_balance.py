def safe_float(value: Any) -> float:
    try:
        number = float(value)
    except (TypeError, ValueError):
        return math.nan
    return number if math.isfinite(number) else math.nan


def asymmetry_pct(left_value: float, right_value: float) -> float:
    """Signed asymmetry; positive means right side is larger than left side."""
    if not math.isfinite(left_value) or not math.isfinite(right_value):
        return math.nan
    denom = (left_value + right_value) / 2.0
    if abs(denom) < 1e-9:
        return math.nan
    return 100.0 * (right_value - left_value) / denom


def annotate_event_metrics(events: pd.DataFrame) -> pd.DataFrame:
    output = events.copy()
    output["estimated_foot_side"] = output["estimated_foot_side"].astype(str).str.lower().str.strip()
    output = output[output["estimated_foot_side"].isin(["left", "right"])].copy()
    output["valid_step_path_length_m"] = pd.to_numeric(output["valid_step_path_length_m"], errors="coerce")
    output["valid_stride_path_length_m"] = pd.to_numeric(output["valid_stride_path_length_m"], errors="coerce")
    output["session_inter_event_interval_s"] = pd.to_numeric(
        output.get("session_inter_event_interval_s", output.get("inter_event_interval_s")),
        errors="coerce",
    )
    output["device_path_forward_alignment"] = pd.to_numeric(output["device_path_forward_alignment"], errors="coerce")
    output["foot_side_alignment"] = pd.to_numeric(output["foot_side_alignment"], errors="coerce")
    output["abs_foot_side_alignment"] = output["foot_side_alignment"].abs()
    output["group_key"] = (
        output["trial_id"].astype(str)
        + "_g"
        + output["continuous_locomotion_group_id"].astype(str)
        + "_"
        + output["label"].astype(str)
    )
    output = output.sort_values(["trial_id", "continuous_locomotion_group_id", "session_s"]).reset_index(drop=True)

    output["event_number_in_run"] = output.groupby(["trial_id", "continuous_locomotion_group_id"]).cumcount()
    output["run_start_s"] = output.groupby(["trial_id", "continuous_locomotion_group_id"])["session_s"].transform("min")
    output["time_from_run_start_s"] = output["session_s"] - output["run_start_s"]
    grouped = output.groupby(["trial_id", "continuous_locomotion_group_id"], sort=False)
    output["rolling4_step_mean_m"] = grouped["valid_step_path_length_m"].transform(
        lambda values: values.rolling(4, min_periods=2).mean()
    )
    output["rolling4_step_std_m"] = grouped["valid_step_path_length_m"].transform(
        lambda values: values.rolling(4, min_periods=2).std()
    )
    output["rolling4_step_cv"] = output["rolling4_step_std_m"] / output["rolling4_step_mean_m"]
    output["rolling4_interval_mean_s"] = grouped["session_inter_event_interval_s"].transform(
        lambda values: values.rolling(4, min_periods=2).mean()
    )
    output["rolling4_interval_std_s"] = grouped["session_inter_event_interval_s"].transform(
        lambda values: values.rolling(4, min_periods=2).std()
    )
    output["rolling4_interval_cv"] = output["rolling4_interval_std_s"] / output["rolling4_interval_mean_s"]

    confidence_ok = output["event_confidence"].isin(["high", "medium"]) & output["foot_side_confidence"].isin(["high", "medium"])
    output["stable_state_candidate"] = (
        (output["event_number_in_run"] >= 4)
        & (output["rolling4_step_cv"] <= 0.25)
        & (output["rolling4_interval_cv"] <= 0.30)
        & (output["device_path_forward_alignment"] >= 0.45)
        & confidence_ok
    )
    return output


def build_group_summary(events: pd.DataFrame) -> pd.DataFrame:
    rows: list[dict[str, Any]] = []
    for (trial_id, group_id), group in events.groupby(["trial_id", "continuous_locomotion_group_id"], sort=False):
        group = group.sort_values("session_s")
        label = str(group["label"].iloc[0])
        left_steps = group.loc[group["estimated_foot_side"] == "left", "valid_step_path_length_m"].dropna()
        right_steps = group.loc[group["estimated_foot_side"] == "right", "valid_step_path_length_m"].dropna()
        left_intervals = group.loc[group["estimated_foot_side"] == "left", "session_inter_event_interval_s"].dropna()
        right_intervals = group.loc[group["estimated_foot_side"] == "right", "session_inter_event_interval_s"].dropna()
        left_count = int((group["estimated_foot_side"] == "left").sum())
        right_count = int((group["estimated_foot_side"] == "right").sum())
        stable = group[group["stable_state_candidate"]].copy()
        if not stable.empty:
            stable_start_s = float(stable["session_s"].iloc[0])
            recovery_time_s = float(stable["time_from_run_start_s"].iloc[0])
        else:
            stable_start_s = math.nan
            recovery_time_s = math.nan
        rows.append(
            {
                "trial_id": trial_id,
                "continuous_locomotion_group_id": int(group_id),
                "label": label,
                "run_start_s": float(group["session_s"].min()),
                "run_end_s": float(group["session_s"].max()),
                "duration_s": float(group["session_s"].max() - group["session_s"].min()),
                "event_count": int(len(group)),
                "left_event_count": left_count,
                "right_event_count": right_count,
                "left_right_count_balance_pct": 100.0 * (right_count - left_count) / max(1, left_count + right_count),
                "left_median_step_m": float(left_steps.median()) if not left_steps.empty else math.nan,
                "right_median_step_m": float(right_steps.median()) if not right_steps.empty else math.nan,
                "step_length_right_minus_left_pct": asymmetry_pct(
                    float(left_steps.median()) if not left_steps.empty else math.nan,
                    float(right_steps.median()) if not right_steps.empty else math.nan,
                ),
                "left_median_interval_s": float(left_intervals.median()) if not left_intervals.empty else math.nan,
                "right_median_interval_s": float(right_intervals.median()) if not right_intervals.empty else math.nan,
                "step_timing_right_minus_left_pct": asymmetry_pct(
                    float(left_intervals.median()) if not left_intervals.empty else math.nan,
                    float(right_intervals.median()) if not right_intervals.empty else math.nan,
                ),
                "median_abs_foot_side_alignment": float(group["abs_foot_side_alignment"].median()),
                "median_device_path_forward_alignment": float(group["device_path_forward_alignment"].median()),
                "high_or_medium_foot_side_fraction": float(group["foot_side_confidence"].isin(["high", "medium"]).mean()),
                "stable_state_start_s": stable_start_s,
                "recovery_time_to_stable_s": recovery_time_s,
            }
        )
    return pd.DataFrame(rows)


def build_trial_label_summary(group_summary: pd.DataFrame) -> pd.DataFrame:
    if group_summary.empty:
        return pd.DataFrame()
    summary = (
        group_summary.groupby(["trial_id", "label"])
        .agg(
            continuous_runs=("continuous_locomotion_group_id", "count"),
            median_abs_step_asymmetry_pct=("step_length_right_minus_left_pct", lambda values: float(values.abs().median())),
            median_signed_step_asymmetry_pct=("step_length_right_minus_left_pct", "median"),
            median_abs_timing_asymmetry_pct=("step_timing_right_minus_left_pct", lambda values: float(values.abs().median())),
            median_recovery_time_s=("recovery_time_to_stable_s", "median"),
            stable_run_fraction=("recovery_time_to_stable_s", lambda values: float(values.notna().mean())),
            median_orientation_side_alignment=("median_abs_foot_side_alignment", "median"),
            median_forward_alignment=("median_device_path_forward_alignment", "median"),
        )
        .reset_index()
    )
    return summary


def build_orientation_summary(events: pd.DataFrame) -> pd.DataFrame:
    if events.empty:
        return pd.DataFrame()
    return (
        events.groupby(["trial_id", "label", "foot_side_confidence"])
        .agg(
            event_count=("session_s", "count"),
            median_abs_foot_side_alignment=("abs_foot_side_alignment", "median"),
            median_forward_alignment=("device_path_forward_alignment", "median"),
            median_step_m=("valid_step_path_length_m", "median"),
        )
        .reset_index()
    )


def save_table(df: pd.DataFrame, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(path, index=False)


def plot_step_length_boxplot(events: pd.DataFrame, out_dir: Path) -> None:
    usable = events[events["valid_step_path_length_m"].notna()].copy()
    usable = usable[usable["foot_side_confidence"].isin(["high", "medium"])]
    if usable.empty:
        return
    keys = []
    data = []
    colors = []
    for (trial_id, label, side), part in usable.groupby(["trial_id", "label", "estimated_foot_side"]):
        if len(part) < 3:
            continue
        keys.append(f"{trial_id}\n{label}\n{side}")
        data.append(part["valid_step_path_length_m"].to_numpy())
        colors.append(SIDE_COLORS.get(side, "#888888"))
    if not data:
        return
    fig_width = max(10, min(24, len(data) * 0.72))
    fig, ax = plt.subplots(figsize=(fig_width, 6.4))
    box = ax.boxplot(data, labels=keys, patch_artist=True, showfliers=False)
    for patch, color in zip(box["boxes"], colors):
        patch.set_facecolor(color)
        patch.set_alpha(0.42)
    ax.set_title("Left/right step-proxy length by trial and motion label")
    ax.set_ylabel("valid step-proxy path length (m)")
    ax.grid(axis="y", alpha=0.25)
    ax.tick_params(axis="x", labelrotation=35, labelsize=8)
    fig.tight_layout()
    fig.savefig(out_dir / "01_left_right_step_length_boxplot.png", dpi=180)
    plt.close(fig)


def plot_asymmetry_by_run(group_summary: pd.DataFrame, out_dir: Path) -> None:
    usable = group_summary[group_summary["step_length_right_minus_left_pct"].notna()].copy()
    if usable.empty:
        return
    usable["run_label"] = usable.apply(
        lambda row: f"{row['trial_id']} {row['label']} {row['run_start_s']:.0f}s",
        axis=1,
    )
    fig_width = max(11, min(28, len(usable) * 0.42))
    fig, ax = plt.subplots(figsize=(fig_width, 6.2))
    colors = [LABEL_COLORS.get(label, "#94a3b8") for label in usable["label"]]
    ax.bar(usable["run_label"], usable["step_length_right_minus_left_pct"], color=colors, alpha=0.82)
    ax.axhline(0, color="#111827", linewidth=1)
    ax.axhline(10, color="#9f1239", linewidth=1, linestyle="--", alpha=0.65)
    ax.axhline(-10, color="#9f1239", linewidth=1, linestyle="--", alpha=0.65)
    ax.set_title("Signed left/right step-length asymmetry by continuous locomotion run")
    ax.set_ylabel("right minus left step length (%)")
    ax.set_xlabel("continuous run")
    ax.grid(axis="y", alpha=0.22)
    ax.tick_params(axis="x", labelrotation=70, labelsize=7)
    fig.tight_layout()
    fig.savefig(out_dir / "02_step_length_asymmetry_by_run.png", dpi=180)
    plt.close(fig)


def plot_orientation_alignment(events: pd.DataFrame, out_dir: Path, trial_id: str = "Ntrial3") -> None:
    part = events[events["trial_id"] == trial_id].copy()
    if part.empty:
        return
    fig, axes = plt.subplots(2, 1, figsize=(16, 8), sharex=True)
    for label, label_part in part.groupby("label"):
        axes[0].scatter(
            label_part["session_s"],
            label_part["abs_foot_side_alignment"],
            s=32,
            alpha=0.78,
            color=LABEL_COLORS.get(label, "#94a3b8"),
            label=label,
        )
        axes[1].scatter(
            label_part["session_s"],
            label_part["device_path_forward_alignment"],
            s=32,
            alpha=0.78,
            color=LABEL_COLORS.get(label, "#94a3b8"),
            label=label,
        )
    axes[0].axhline(0.70, color="#14523c", linestyle="--", linewidth=1, label="strong side mapping threshold")
    axes[0].axhline(0.45, color="#8a4b05", linestyle="--", linewidth=1, label="weak/medium boundary")
    axes[0].set_ylabel("|foot-side alignment|")
    axes[0].set_title(f"{trial_id}: orientation support for left/right foot-side estimate")
    axes[0].grid(alpha=0.22)
    axes[0].legend(loc="best", frameon=True, fontsize=8)
    axes[1].axhline(0.55, color="#14523c", linestyle="--", linewidth=1, label="good forward alignment")
    axes[1].set_ylabel("device-forward/path alignment")
    axes[1].set_xlabel("session time (s)")
    axes[1].grid(alpha=0.22)
    axes[1].legend(loc="best", frameon=True, fontsize=8)
    fig.tight_layout()
    fig.savefig(out_dir / f"03_orientation_alignment_over_time_{trial_id}.png", dpi=180)
    plt.close(fig)


def plot_recovery_timeline(events: pd.DataFrame, group_summary: pd.DataFrame, out_dir: Path, trial_id: str = "Ntrial3") -> None:
    part = events[events["trial_id"] == trial_id].copy()
    if part.empty:
        return
    fig, axes = plt.subplots(2, 1, figsize=(16, 8), sharex=True)
    for side, side_part in part.groupby("estimated_foot_side"):
        axes[0].scatter(
            side_part["session_s"],
            side_part["valid_step_path_length_m"],
            s=42,
            alpha=0.82,
            color=SIDE_COLORS.get(side, "#888888"),
            label=side,
        )
    stable_part = part[part["stable_state_candidate"]]
    if not stable_part.empty:
        axes[0].scatter(
            stable_part["session_s"],
            stable_part["valid_step_path_length_m"],
            s=90,
            facecolors="none",
            edgecolors="#111827",
            linewidths=1.4,
            label="stable-state candidate events",
        )
    trial_groups = group_summary[group_summary["trial_id"] == trial_id]
    for _, row in trial_groups.iterrows():
        stable_s = safe_float(row.get("stable_state_start_s"))
        if math.isfinite(stable_s):
            axes[0].axvline(stable_s, color="#14523c", linestyle="--", linewidth=1, alpha=0.55)
            axes[1].axvline(stable_s, color="#14523c", linestyle="--", linewidth=1, alpha=0.55)
    axes[0].set_title(f"{trial_id}: left/right step length and candidate stable walking state")
    axes[0].set_ylabel("step-proxy path length (m)")
    axes[0].grid(alpha=0.22)
    axes[0].legend(loc="best", frameon=True, fontsize=8)

    axes[1].plot(part["session_s"], part["rolling4_step_cv"], color="#7a4fb3", linewidth=1.8, label="rolling last-4 step-length CV")
    axes[1].plot(part["session_s"], part["rolling4_interval_cv"], color="#d95f02", linewidth=1.5, label="rolling last-4 interval CV")
    axes[1].axhline(0.25, color="#7a4fb3", linestyle="--", linewidth=1, alpha=0.6)
    axes[1].axhline(0.30, color="#d95f02", linestyle="--", linewidth=1, alpha=0.6)
    axes[1].set_ylabel("rolling variability")
    axes[1].set_xlabel("session time (s)")
    axes[1].grid(alpha=0.22)
    axes[1].legend(loc="best", frameon=True, fontsize=8)
    fig.tight_layout()
    fig.savefig(out_dir / f"04_recovery_state_timeline_{trial_id}.png", dpi=180)
    plt.close(fig)


