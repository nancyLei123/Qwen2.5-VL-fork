def write_readme(out_dir: Path, group_summary: pd.DataFrame, trial_summary: pd.DataFrame) -> None:
    n_runs = len(group_summary)
    stable_fraction = float(group_summary["recovery_time_to_stable_s"].notna().mean()) if n_runs else math.nan
    median_abs_asym = (
        float(group_summary["step_length_right_minus_left_pct"].abs().median())
        if n_runs and group_summary["step_length_right_minus_left_pct"].notna().any()
        else math.nan
    )
    median_recovery = (
        float(group_summary["recovery_time_to_stable_s"].median())
        if n_runs and group_summary["recovery_time_to_stable_s"].notna().any()
        else math.nan
    )
    trial_summary_text = trial_summary.round(3).to_string(index=False) if not trial_summary.empty else "No summary rows."
    readme = f"""# Left/Right Balance And Orientation Exploration

This folder explores whether the current SLAM-derived step proxies can say something about left/right balance, orientation, and a possible stable walking/recovery state.

## Data Used

- Input events: `runs/stride_step_diagnostics/data/step_stride_event_estimates.csv`
- Each event is a SLAM head-motion step proxy, not a direct foot-contact label.
- `estimated_foot_side` is inferred from side-to-side head sway plus Aria/device orientation. It should be treated as an initial estimate and checked with the downward video.

## What We Did

1. **Left/right balance**
   - Split events by `estimated_foot_side` = left or right.
   - Compared valid step-proxy length between left and right events.
   - Calculated signed asymmetry:
     `100 * (right_median - left_median) / average(left_median, right_median)`.
   - Positive value means right-side step proxy is larger; negative means left-side step proxy is larger.

2. **Orientation support**
   - Used `foot_side_alignment` to ask whether Aria/head orientation supports the left/right mapping.
   - Used `device_path_forward_alignment` to ask whether the device forward direction agrees with the path direction.
   - This matters because turns or head rotations can make left/right estimates less reliable.

3. **Stable walking/recovery state**
   - For each continuous locomotion run, calculated rolling last-4-step variability.
   - A candidate stable state is marked when:
     - at least 4 step events have happened,
     - rolling step-length CV <= 0.25,
     - rolling step-interval CV <= 0.30,
     - device/path forward alignment >= 0.45,
     - event and foot-side confidence are not low.
   - This is only a first candidate rule, but it gives us a concrete way to discuss “recovery” after movement starts.

## Main Outputs

- `left_right_event_metrics.csv`: event-level table with rolling variability and stable-state flags.
- `left_right_group_summary.csv`: one row per continuous locomotion run.
- `left_right_trial_label_summary.csv`: trial-level summary by motion label.
- `orientation_confidence_summary.csv`: orientation-confidence summary.

## Quick Overall Reading

- Continuous locomotion runs analyzed: {n_runs}
- Fraction of runs with a candidate stable state: {stable_fraction:.2%}
- Median absolute left/right step-length asymmetry: {median_abs_asym:.2f}%
- Median time to candidate stable state: {median_recovery:.2f} s

## Trial/Label Summary

```text
{trial_summary_text}
```

## Important Interpretation

This is a reasonable first exploration, but it is not yet a clinical gait-balance measurement. The left/right side is estimated from head/device motion and orientation. It is most trustworthy when orientation alignment is high and the user is walking relatively straight. During turns, head motions, stairs, or low-confidence events, the left/right estimate should be validated with the downward video.
"""
    (out_dir / "README.md").write_text(readme)


def main() -> None:
    args = parse_args()
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    events_path = Path(args.events_csv)
    if not events_path.exists():
        raise FileNotFoundError(f"Missing events CSV: {events_path}")
    events = pd.read_csv(events_path)
    if args.trials:
        events = events[events["trial_id"].astype(str).isin(args.trials)].copy()

    annotated = annotate_event_metrics(events)
    group_summary = build_group_summary(annotated)
    trial_summary = build_trial_label_summary(group_summary)
    orientation_summary = build_orientation_summary(annotated)

    save_table(annotated, out_dir / "left_right_event_metrics.csv")
    save_table(group_summary, out_dir / "left_right_group_summary.csv")
    save_table(trial_summary, out_dir / "left_right_trial_label_summary.csv")
    save_table(orientation_summary, out_dir / "orientation_confidence_summary.csv")

    plot_dir = out_dir / "plots"
    plot_dir.mkdir(exist_ok=True)
    plot_step_length_boxplot(annotated, plot_dir)
    plot_asymmetry_by_run(group_summary, plot_dir)
    plot_orientation_alignment(annotated, plot_dir, "Ntrial3")
    plot_recovery_timeline(annotated, group_summary, plot_dir, "Ntrial3")
    plot_recovery_time_by_run(group_summary, plot_dir)

    write_readme(out_dir, group_summary, trial_summary)
    print(f"Wrote left/right orientation exploration to {out_dir}")
    if not trial_summary.empty:
        print(trial_summary.round(3).to_string(index=False))


if __name__ == "__main__":
    main()
