"""Plan, or explicitly run after the GPU suite, qualitative deployed-Ply checks.

The old models trained on most of the five fixed experiment views. These scores
are NON-HELD-OUT references, never eligible for promotion or generalization claims.
Default invocation is read-only. --run is required to call the native evaluator.
After the complete suite: python -B scripts/check_aria_deployed_quality.py --run --contact-sheets
All results go to <experiment>/deployed_reference; existing output is refused.
"""

from __future__ import annotations

import argparse
import copy
import json
import math
import os
from pathlib import Path
import re
import shutil

import numpy as np
from PIL import Image

import compare_aria_gaussian_quality as quality


LABEL = "Qualitative / non-held-out deployed reference"
LIMITS = [
    "Old training used most of the five fixed views; scores are not fair held-out comparisons to retrained models.",
    "Original held-out means excluded from original optimization only; MPS geometry and initializer colors are not independently held out.",
    "Replay compares decoded RGB PNG pixels at the original held-out camera, not the offset scene_view.camera_position.",
    "Replay tolerance is at most one 8-bit code value per channel at every pixel; this validates one view, not every pose or the WebGL viewer.",
    "Original logged PSNR may precede PNG quantization; it is context, not the replay pass/fail criterion.",
    "Baseline and long30k use different training schedules; they are recipe comparisons, not an isolated iteration ablation or replicated statistical study.",
    "A replay mismatch is not proof of a loader bug: backend/build, image pipeline, camera conventions and serialization all require investigation.",
    "No retraining, promotion, original-asset changes, enhancement or uploads are performed by this script.",
]


def read_json(path):
    return json.loads(Path(path).read_text())


def json_finite(value):
    if isinstance(value, dict):
        return {key: json_finite(item) for key, item in value.items()}
    if isinstance(value, list):
        return [json_finite(item) for item in value]
    return None if isinstance(value, float) and not math.isfinite(value) else value


def save(path, value):
    quality.save_json(path, json_finite(value))


def contained(path, root):
    resolved = Path(path).resolve(strict=True)
    if not resolved.is_relative_to(Path(root).resolve(strict=True)):
        raise ValueError(f"Input escaped its expected directory: {path}")
    return resolved


def checkpoint_info(path):
    """Fail closed before --resume can accidentally enter the training loop."""
    with Path(path).open("rb") as stream:
        lines = []
        while stream.tell() < 65536:
            line = stream.readline(65537 - stream.tell())
            if not line or stream.tell() > 65536:
                raise ValueError("Missing/oversized OpenSplat PLY header")
            lines.append(line.decode("ascii").rstrip("\r\n"))
            if lines[-1] == "end_header":
                break
        else:
            raise ValueError("Missing/oversized OpenSplat PLY header")
        header_bytes = stream.tell()
    if len(lines) < 5 or lines[:2] != ["ply", "format binary_little_endian 1.0"]:
        raise ValueError("Expected a native binary little-endian OpenSplat checkpoint")
    iteration = re.fullmatch(r"comment Generated by opensplat at iteration (\d+)", lines[2])
    vertices = re.fullmatch(r"element vertex (\d+)", lines[3])
    expected = ["x", "y", "z", "nx", "ny", "nz"] + [f"f_dc_{i}" for i in range(3)]
    expected += [f"f_rest_{i}" for i in range(45)] + ["opacity"]
    expected += [f"scale_{i}" for i in range(3)] + [f"rot_{i}" for i in range(4)]
    if not iteration or not vertices or lines[4:-1] != [f"property float {name}" for name in expected]:
        raise ValueError("Only canonical SH3 OpenSplat checkpoints are supported by the reused evaluator")
    step, count = int(iteration[1]), int(vertices[1])
    if step <= 0 or count <= 0 or Path(path).stat().st_size != header_bytes + count * len(expected) * 4:
        raise ValueError("Invalid checkpoint step, vertex count or payload size")
    return {"step": step, "vertices": count, "sh_degree": 3}


def view_names(items):
    names = [item["name"] for item in items]
    if len(names) != len(set(names)) or any(not name or name in (".", "..") or Path(name).name != name for name in names):
        raise ValueError("View names must be unique image basenames")
    return names


def verify_hashes(hashes):
    changed = [path for path, digest in hashes.items()
               if not Path(path).is_file() or quality.sha256(path) != digest]
    if changed:
        raise RuntimeError(f"Protected inputs changed: {changed}")


def load_scene(experiment, scene):
    split_path = experiment / scene / "split.json"
    split = read_json(split_path)
    source = contained(split["source"], quality.ENV / "gaussian_submaps" / scene)
    manifest_path = source / "dataset_manifest.json"
    manifest = read_json(manifest_path)
    summary_path = source / "trained_7000_fullres/training_summary.json"
    summary = read_json(summary_path)
    if split["scene"] != scene or len(split["validation"]) != 5:
        raise ValueError("Expected the scene's saved five-view split")
    names = view_names(split["validation"])
    frames = {item["name"]: item for item in manifest["frames"]["items"]}
    if len(frames) != len(manifest["frames"]["items"]):
        raise ValueError("Duplicate source frame names")
    if split["camera"] != manifest["camera"] or split["world_frame"] != manifest["world_frame"]:
        raise ValueError("Split camera/world frame does not match original data")
    if any(item != frames.get(item["name"]) for item in split["validation"]):
        raise ValueError("Fixed views differ from original camera records")
    held_name = summary["validation_image"]
    if held_name not in frames or summary.get("scene_view", {}).get("validation_image", held_name) != held_name:
        raise ValueError("Original held-out camera cannot be resolved unambiguously")
    parameters = summary["training_parameters"]
    command = summary["command"]
    val_index = command.index("--val-image") if "--val-image" in command else -2
    if "--val" not in command or command[val_index + 1:val_index + 2] != [held_name]:
        raise ValueError("Original command does not confirm the claimed optimization holdout")
    if (summary["downscale_factor"] != 1 or parameters["spherical_harmonics_degree"] != 3
            or parameters["spherical_harmonics_degree_interval"] != 1000
            or any(arg.split("=")[0] == "--center" for arg in command)):
        raise ValueError("Original training settings are incompatible with the reused evaluator")
    ply = contained(summary_path.parent / summary["viewer_splat_filename"], summary_path.parent)
    if ply != Path(summary["splat_ply"]).resolve():
        raise ValueError("Original deployed filename disagrees with training_summary.splat_ply")
    header = checkpoint_info(ply)
    if header["step"] != summary["iterations"]:
        raise ValueError("PLY iteration differs from summary; refusing any possible training steps")
    held_render = contained(summary["held_out_render"], summary_path.parent)
    c = manifest["camera"]
    with Image.open(held_render) as image:
        if image.size != (c["width"], c["height"]):
            raise ValueError("Original held-out PNG resolution differs from the evaluation camera")
    eval_dir = contained(experiment / scene / "eval", experiment / scene)
    inputs = [split_path, manifest_path, summary_path, ply, held_render]
    inputs += list((eval_dir / "sparse/0").glob("*"))
    for filename in ("cameras.bin", "images.bin", "points3D.bin"):
        if not (eval_dir / "sparse/0" / filename).is_file():
            raise ValueError("The suite's native evaluation dataset is incomplete")
    for name in set(names + [held_name]):
        reference = contained(source / "images" / name, source)
        if quality.sha256(eval_dir / "images" / name) != quality.sha256(reference):
            raise ValueError("Evaluation image differs from the original reference")
        inputs.append(reference)
    hashes = dict(split["source_sha256"])
    verify_hashes(hashes)
    hashes.update({str(path): quality.sha256(path) for path in inputs if path.is_file()})
    verify_hashes(hashes)
    return {"id": scene, "split": split, "summary": summary, "ply": str(ply),
            "eval_dir": str(eval_dir), "held_view": frames[held_name], "held_render": str(held_render),
            "checkpoint": header, "original_training_overlap": [name != held_name for name in names],
            "protected_sha256": hashes}


def suite_scores(experiment, scene):
    scores = {}
    for recipe, step in (("baseline_7000", 7000), ("long_30000", 30000)):
        scores[recipe] = read_json(experiment / scene / recipe / f"eval_{step}" / "metrics.json")
    return scores


def require_suite_complete(experiment, binary):
    progress = read_json(experiment / "progress.json")
    if (progress.get("state") != "complete" or not set(quality.SCENES).issubset(progress.get("scenes", []))
            or not set(quality.RECIPES).issubset(progress.get("recipes", []))):
        raise RuntimeError("GPU suite is not complete for all scenes/recipes; no rendering is allowed")
    for scene in quality.SCENES:
        names = view_names(read_json(experiment / scene / "split.json")["validation"])
        for recipe_name, recipe in quality.RECIPES.items():
            directory = experiment / scene / recipe_name
            run = read_json(directory / "run.json")
            if run["recipe"] != recipe or run["binary_sha256"] != quality.sha256(binary):
                raise RuntimeError("Completed suite recipe/binary does not match the requested replay")
            for step in recipe["checkpoints"]:
                score = read_json(directory / f"eval_{step}" / "metrics.json")
                if view_names(score["views"]) != names or any(not Path(v["render"]).is_file() for v in score["views"]):
                    raise RuntimeError("Suite's five-view native render outputs are incomplete")


def build_plan(experiment, binary):
    experiment, binary = Path(experiment).resolve(strict=True), Path(binary).resolve(strict=True)
    if experiment.parent != quality.ENV.resolve():
        raise ValueError("Experiment must be a direct child of environment_reconstruction")
    scenes = [load_scene(experiment, scene) for scene in quality.SCENES]
    return {"schema_version": 1, "label": LABEL, "eligible_for_promotion": False,
            "experiment": str(experiment), "output": str(experiment / "deployed_reference"),
            "binary": str(binary), "binary_sha256": quality.sha256(binary),
            "evaluator_sha256": quality.sha256(Path(quality.__file__)),
            "script_sha256": quality.sha256(Path(__file__)), "scenes": scenes, "limits": LIMITS}


def compare_replay(original_render, replay_render):
    with Image.open(original_render) as a, Image.open(replay_render) as b:
        if a.size != b.size:
            raise ValueError("Replay dimensions differ; resizing would invalidate the check")
        original, replay = np.asarray(a.convert("RGB")), np.asarray(b.convert("RGB"))
        values = quality.metrics(a, b)
    delta = np.abs(original.astype(np.int16) - replay.astype(np.int16))
    maximum = int(delta.max())
    return {"comparison": "loaded checkpoint PNG versus original training-time held-out PNG",
            "original_render": str(original_render), "original_render_sha256": quality.sha256(original_render),
            "replay_render": str(replay_render), "replay_render_sha256": quality.sha256(replay_render),
            "exact_pixels_equal": maximum == 0, "within_one_code_value": maximum <= 1,
            "max_abs_error_rgb8": maximum, "mean_abs_error_rgb8": float(delta.mean()),
            "fraction_pixels_different": float(np.any(delta != 0, axis=2).mean()),
            "status": "exact" if maximum == 0 else "within_one_code_value" if maximum <= 1 else "mismatch",
            "metrics": json_finite(values)}


def audit_resume_loader(cpp_path):
    """Read-only diagnostics; source findings do not establish a pixel-error cause."""
    path = Path(cpp_path)
    if not path.is_file():
        return {"status": "source_unavailable", "path": str(path)}
    lines = path.read_text().splitlines()
    patterns = {
        "header_byte_accounting": "bytesRead += f.gcount()",
        "payload_size_branch": "if (remainingFileSize != bytesPerPoint * numPoints)",
        "load_sh_channel_order": "featuresRestCpu.reshape({numPoints, 3, featuresRestSize/3}).transpose(2, 1)",
        "save_sh_channel_order": "featuresRest.cpu().transpose(1, 2).reshape({numPoints, -1})",
    }
    evidence = {key: [{"line": i, "text": line.strip()} for i, line in enumerate(lines, 1) if pattern in line]
                for key, pattern in patterns.items()}
    return {"status": "read_only_source_audit", "path": str(path), "sha256": quality.sha256(path),
            "evidence": evidence,
            "concerns": [
                "If present, gcount() following std::getline(string) does not account for extracted header bytes; coefficient-prefix reads also omit accounting.",
                "If present, the != payload-size branch enters loading rather than rejection, so the loader's size check is not reliable. This script independently validates the exact payload size.",
                "If both save/load SH patterns are present, their channel transposes are inverse layouts; these lines do not establish an SH ordering mismatch.",
                "These are source observations, not proof of which source built the current binary or what caused a render mismatch.",
            ]}


def contact_sheet(scene, deployed, other_scores, destination, replay_status):
    os.environ.setdefault("MPLCONFIGDIR", str(Path(destination).parent / ".matplotlib"))
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fixed = scene["split"]["validation"]
    names = view_names(fixed)
    scores = [deployed, other_scores["baseline_7000"], other_scores["long_30000"]]
    if len(names) != 5 or any(view_names(score["views"]) != names for score in scores):
        raise ValueError("Contact sheet requires the exact same five ordered views in all columns")
    titles = ["Reference RGB", "Deployed original\nNON-HELD-OUT", "Retrained baseline 7k", "Long recipe 30k"]
    fig, axes = plt.subplots(5, 4, figsize=(16, 20), squeeze=False)
    try:
        for row, item in enumerate(fixed):
            paths = [Path(scene["split"]["source"]) / "images" / item["name"]]
            paths += [Path(score["views"][row]["render"]) for score in scores]
            dimensions = None
            for column, path in enumerate(paths):
                with Image.open(path) as image:
                    rgb = np.array(image.convert("RGB"))
                if dimensions is None:
                    dimensions = rgb.shape
                if rgb.shape != dimensions:
                    raise ValueError("Native contact-sheet images differ in dimensions; no resizing is allowed")
                ax = axes[row, column]
                ax.imshow(rgb, aspect="equal", interpolation="nearest")
                ax.set_xticks([])
                ax.set_yticks([])
                if column:
                    values = scores[column - 1]["views"][row]
                    ax.set_xlabel(f"PSNR {values['psnr_db']:.2f} dB | SSIM {values['ssim']:.4f}", fontsize=9)
                if row == 0:
                    ax.set_title(titles[column], fontsize=12)
                if column == 0:
                    exposure = "old training view" if scene["original_training_overlap"][row] else "old optimization holdout"
                    ax.set_ylabel(f"{item['name']}\n{item['recording_s']:.3f} s\n{exposure}", fontsize=9)
        fig.suptitle(f"{scene['id']} | {LABEL}\nReplay check: {replay_status}; not a fair held-out model ranking", fontsize=13)
        fig.text(0.5, 0.012, "Native renders, no enhancement; aspect preserved (display scaling only). Shared MPS geometry is not independently held out.",
                 ha="center", fontsize=9)
        fig.tight_layout(rect=(0, 0.03, 1, 0.95))
        fig.savefig(destination, dpi=140)
    finally:
        plt.close(fig)


def run_plan(plan, make_contact_sheets=False, cpp_path=None):
    experiment, binary, output = (Path(plan[key]) for key in ("experiment", "binary", "output"))
    require_suite_complete(experiment, binary)
    if output != experiment / "deployed_reference" or output.exists():
        raise FileExistsError("Use a new deployed_reference directory; refusing stale metrics or existing output")
    hashes = {str(binary): plan["binary_sha256"], str(Path(quality.__file__)): plan["evaluator_sha256"]}
    for scene in plan["scenes"]:
        hashes.update(scene["protected_sha256"])
    verify_hashes(hashes)
    output.mkdir()
    save(output / "plan.json", plan)
    results = {"label": LABEL, "eligible_for_promotion": False, "limits": LIMITS, "scenes": []}
    try:
        for scene in plan["scenes"]:
            destination = output / scene["id"]
            # OpenSplat may cache images beside its input dataset, never beside originals here.
            shutil.copytree(scene["eval_dir"], destination / "eval", symlinks=True)
            split = copy.deepcopy(scene["split"])
            split["validation"] = [scene["held_view"]]
            require_suite_complete(experiment, binary)
            verify_hashes(hashes)
            replay = quality.evaluate(binary, destination, split, Path(scene["ply"]), scene["checkpoint"]["step"],
                                      destination / "original_holdout", output / "progress.json")
            if view_names(replay["views"]) != [scene["held_view"]["name"]]:
                raise RuntimeError("Evaluator did not return the original held-out view")
            replay["assessment_kind"] = "original_holdout_replay_check_not_new_generalization"
            save(destination / "original_holdout/metrics.json", replay)
            fidelity = compare_replay(scene["held_render"], replay["views"][0]["render"])
            fidelity["original_logged_validation_psnr_db"] = scene["summary"].get("validation_psnr_db")
            if not fidelity["within_one_code_value"]:
                default_cpp = quality.ROOT.parent / "tools/OpenSplat-1.2.2/model.cpp"
                fidelity["resume_loader_audit"] = audit_resume_loader(cpp_path or default_cpp)
            save(destination / "replay_validation.json", fidelity)
            require_suite_complete(experiment, binary)
            verify_hashes(hashes)
            score = quality.evaluate(binary, destination, scene["split"], Path(scene["ply"]), scene["checkpoint"]["step"],
                                     destination / "fixed_views", output / "progress.json")
            if view_names(score["views"]) != view_names(scene["split"]["validation"]):
                raise RuntimeError("Evaluator did not return the exact saved five views")
            score.update({"label": LABEL, "held_out": False, "eligible_for_promotion": False,
                          "replay_validated_within_one_code_value": fidelity["within_one_code_value"],
                          "interpretation": "Diagnostic only: replay mismatch" if not fidelity["within_one_code_value"] else LIMITS[0]})
            for row, overlap in zip(score["views"], scene["original_training_overlap"]):
                row["used_for_original_optimization"] = overlap
                row["assessment_kind"] = "qualitative_non_held_out_set"
            save(destination / "fixed_views/metrics.json", score)
            record = {"id": scene["id"], "deployed_reference": score, "replay_validation": fidelity}
            if make_contact_sheets:
                sheet = destination / "comparison.png"
                contact_sheet(scene, score, suite_scores(experiment, scene["id"]), sheet, fidelity["status"])
                record["contact_sheet"] = str(sheet)
            verify_hashes(hashes)
            results["scenes"].append(record)
            save(output / "results.json", results)
        save(output / "progress.json", {"state": "complete", "label": LABEL})
    except BaseException as error:
        save(output / "failure.json", {"error": str(error), "label": LABEL})
        save(output / "progress.json", {"state": "failed", "error": str(error), "label": LABEL})
        raise
    finally:
        verify_hashes(hashes)
    return output / "results.json"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--experiment-dir", type=Path, default=quality.DEFAULT_OUTPUT)
    parser.add_argument("--binary", type=Path, default=quality.DEFAULT_BINARY)
    parser.add_argument("--run", action="store_true", help="Explicitly render, only after the whole suite is complete")
    parser.add_argument("--contact-sheets", action="store_true", help="Write five-row static Matplotlib comparison PNGs with --run")
    args = parser.parse_args(argv)
    plan = build_plan(args.experiment_dir, args.binary)
    if args.run:
        print(run_plan(plan, args.contact_sheets))
    else:
        print(json.dumps({"mode": "read_only_plan_no_gpu", "output": plan["output"], "label": LABEL,
                          "suite_progress": read_json(args.experiment_dir / "progress.json"),
                          "scenes": [{"id": s["id"], "ply": s["ply"], "fixed_views": view_names(s["split"]["validation"]),
                                      "old_training_view_count": sum(s["original_training_overlap"]),
                                      "original_holdout": s["held_view"]["name"]} for s in plan["scenes"]],
                          "limits": LIMITS}, indent=2))


if __name__ == "__main__":
    main()
