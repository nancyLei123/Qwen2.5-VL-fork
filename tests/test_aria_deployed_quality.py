@pytest.mark.parametrize("error, status", [(0, "exact"), (1, "within_one_code_value"), (2, "mismatch")])
def test_replay_uses_decoded_pixels_and_explicit_one_lsb_tolerance(tmp_path, error, status):
    original, replay = tmp_path / "original.png", tmp_path / "replay.png"
    rgb = np.full((8, 12, 3), 100, dtype=np.uint8)
    Image.fromarray(rgb).save(original, compress_level=0)
    rgb[2, 3, 1] += error
    Image.fromarray(rgb).save(replay, compress_level=9)
    comparison = deployed.compare_replay(original, replay)
    assert comparison["original_render_sha256"] != comparison["replay_render_sha256"]
    assert comparison["status"] == status
    assert comparison["max_abs_error_rgb8"] == error
    assert comparison["within_one_code_value"] == (error <= 1)
    assert comparison["fraction_pixels_different"] == (1 / 96 if error else 0)


