    split_path = experiment["experiment"] / experiment["scene"] / "split.json"
    split = deployed.read_json(split_path)
    summary = deployed.read_json(experiment["summary_path"])
    if change == "camera":
        split["camera"]["fx"] += 1
    elif change == "pose":
        split["validation"][0]["T_world_camera"][0][3] += 1
    elif change == "duplicate":
        split["validation"][1] = copy.deepcopy(split["validation"][0])
    elif change == "resolution":
        summary["downscale_factor"] = 2
    elif change == "sh_degree":
        summary["training_parameters"]["spherical_harmonics_degree"] = 2
    elif change == "center":
        summary["command"].append("--center")
    else:
        summary["command"][-1] = "wrong.png"
    deployed.save(split_path, split)
    deployed.save(experiment["summary_path"], summary)
    with pytest.raises(ValueError):
        plan_for(experiment)


