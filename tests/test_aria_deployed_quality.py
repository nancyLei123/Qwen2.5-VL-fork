def plan_for(experiment):
    return deployed.build_plan(experiment["experiment"], experiment["binary"])


def stub_native(monkeypatch, experiment, replay_error=0):
    calls = []

    def execute(command, log, status_path, stage, total=None):
        calls.append(command)
        assert total is None
        assert command[command.index("-n") + 1] == "7000"
        assert command[command.index("--resume") + 1] == str(experiment["ply"])
        assert command[command.index("--sh-degree") + 1] == "3"
        assert command[command.index("-d") + 1] == "1"
        dataset = Path(command[1])
        assert dataset.is_relative_to(experiment["experiment"] / "deployed_reference")
        for filename in ("cameras.bin", "images.bin", "points3D.bin"):
            assert (dataset / "sparse/0" / filename).read_bytes() == (
                experiment["experiment"] / experiment["scene"] / "eval/sparse/0" / filename).read_bytes()
        name = command[command.index("--val-image") + 1]
        held_name = deployed.read_json(experiment["summary_path"])["validation_image"]
        source = experiment["held_render"] if name == held_name else experiment["source"] / "images" / name
        with Image.open(source) as image:
            rgb = np.array(image)
        if name == held_name:
            rgb[0, 0, 0] += replay_error
        renders = Path(command[command.index("--val-render") + 1])
        renders.mkdir(parents=True)
        Image.fromarray(rgb).save(renders / "7000.png")
        log.parent.mkdir(parents=True, exist_ok=True)
        text = "Using MPS\nLoaded original checkpoint\n"
        log.write_text(text)
        deployed.save(status_path, {"state": "running", "stage": stage})
        return 0.0, text

    monkeypatch.setattr(deployed.quality, "execute", execute)
    return calls


