def write_checkpoint(path, step=7000):
    properties = ["x", "y", "z", "nx", "ny", "nz"] + [f"f_dc_{i}" for i in range(3)]
    properties += [f"f_rest_{i}" for i in range(45)] + ["opacity"]
    properties += [f"scale_{i}" for i in range(3)] + [f"rot_{i}" for i in range(4)]
    header = ["ply", "format binary_little_endian 1.0",
              f"comment Generated by opensplat at iteration {step}", "element vertex 2"]
    header += [f"property float {name}" for name in properties] + ["end_header"]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(("\n".join(header) + "\n").encode("ascii") + np.arange(2 * len(properties), dtype="<f4").tobytes())


def snapshot(root):
    return {str(path.relative_to(root)): deployed.quality.sha256(path)
            for path in root.rglob("*") if path.is_file()}


