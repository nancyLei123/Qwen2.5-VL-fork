def test_contact_sheet_all_five_views_native_pixels_aspect_and_labels(experiment, monkeypatch, tmp_path):
    monkeypatch.setenv("MPLCONFIGDIR", str(tmp_path / "matplotlib"))
    import matplotlib
    matplotlib.use("Agg")
    from matplotlib.axes import Axes
    from matplotlib.figure import Figure

    shown, text = [], []
    original_imshow, original_suptitle, original_title = Axes.imshow, Figure.suptitle, Axes.set_title

    def imshow(self, data, *args, **kwargs):
        shown.append((np.array(data), kwargs))
        return original_imshow(self, data, *args, **kwargs)

    def suptitle(self, value, *args, **kwargs):
        text.append(value)
        return original_suptitle(self, value, *args, **kwargs)

    def title(self, value, *args, **kwargs):
        text.append(value)
        return original_title(self, value, *args, **kwargs)

    monkeypatch.setattr(Axes, "imshow", imshow)
    monkeypatch.setattr(Figure, "suptitle", suptitle)
    monkeypatch.setattr(Axes, "set_title", title)
    stub_native(monkeypatch, experiment)
    result = deployed.read_json(deployed.run_plan(plan_for(experiment), make_contact_sheets=True))
    scene = result["scenes"][0]
    assert Path(scene["contact_sheet"]).is_file()
    assert len(shown) == 20
    suite = deployed.suite_scores(experiment["experiment"], experiment["scene"])
    for row, view in enumerate(experiment["split"]["validation"]):
        with Image.open(experiment["source"] / "images" / view["name"]) as image:
            np.testing.assert_array_equal(shown[row * 4][0], np.asarray(image))
        for column, scores in enumerate([scene["deployed_reference"], suite["baseline_7000"], suite["long_30000"]], 1):
            with Image.open(scores["views"][row]["render"]) as image:
                np.testing.assert_array_equal(shown[row * 4 + column][0], np.asarray(image))
    assert all(array.shape == (8, 12, 3) and kwargs["aspect"] == "equal" and kwargs["interpolation"] == "nearest"
               for array, kwargs in shown)
    assert any("NON-HELD-OUT" in value for value in text)
    assert any("not a fair held-out model ranking" in value for value in text)
    assert "Retrained baseline 7k" in text and "Long recipe 30k" in text


